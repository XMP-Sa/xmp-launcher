#!/usr/bin/env python3
"""Fetch the typefaces used by XMP (latin subsets) as .woff2 for the app,
and register them locally so the icon renderer can use them too."""

import os
import re
import subprocess
import urllib.request

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0 Safari/537.36")

RANGE = {
    "latin": ("U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,"
              "U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"),
    "arabic": ("U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,"
               "U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC"),
}

FAMILIES = [
    ("Inter", "Inter:wght@400;500;600;700"),
    ("Sora", "Sora:wght@500;600;700;800"),
    ("Vazirmatn", "Vazirmatn:wght@400;500;600;700"),
]

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "src", "assets", "fonts")
LOCAL = os.path.expanduser("~/.local/share/fonts")
os.makedirs(OUT, exist_ok=True)
os.makedirs(LOCAL, exist_ok=True)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=30).read()


def parse(css):
    """Yield (weight, style, url) for the `latin` subset blocks."""
    blocks = re.findall(r"/\*\s*([a-z0-9\-\[\]]+)\s*\*/\s*@font-face\s*{(.*?)}", css, re.S)
    for subset, body in blocks:
        if subset not in ("latin", "arabic"):
            continue
        weight = re.search(r"font-weight:\s*(\d+)", body)
        style = re.search(r"font-style:\s*(\w+)", body)
        url = re.search(r"url\((https://[^)]+)\)", body)
        if weight and url:
            yield weight.group(1), (style.group(1) if style else "normal"), url.group(1), subset


def main():
    lines = []
    for name, query in FAMILIES:
        css = get(f"https://fonts.googleapis.com/css2?family={query}&display=swap").decode()
        for weight, style, url, subset in parse(css):
            fn = f"{name.lower()}-{weight}-{style}-{subset}.woff2"
            path = os.path.join(OUT, fn)
            if not os.path.exists(path):
                with open(path, "wb") as fh:
                    fh.write(get(url))
            print("saved", fn, os.path.getsize(path))
            lines.append(
                "@font-face{font-family:'%s';font-style:%s;font-weight:%s;"
                "font-display:swap;unicode-range:%s;src:url('../assets/fonts/%s') format('woff2')}"
                % (name, style, weight, RANGE[subset], fn)
            )
            # register a ttf locally for icon rasterisation (Sora only)
            if name == "Sora" and subset == "latin":
                try:
                    from fontTools.ttLib import TTFont
                    f = TTFont(path)
                    f.flavor = None
                    f.save(os.path.join(LOCAL, f"Sora-{weight}.ttf"))
                except Exception as exc:  # pragma: no cover
                    print("warn: could not convert", fn, exc)

    with open(os.path.join(ROOT, "src", "styles", "fonts.css"), "w") as fh:
        fh.write("/* generated by scripts/fetch-fonts.py — do not edit */\n")
        fh.write("\n".join(lines) + "\n")
    subprocess.run(["fc-cache", "-f", LOCAL], check=False)
    print("fonts.css written")


if __name__ == "__main__":
    main()
